// calculator.js — เครื่องคิดเลขอย่างง่าย (โปรเจกต์ตัวอย่างสำหรับฝึก Claude Code)

/** บวกเลขสองจำนวน */
function add(a, b) {
  return a + b;
}

/** ลบเลขสองจำนวน */
function subtract(a, b) {
  return a - b;
}

// แบบฝึก Lab 02: ลองให้ Claude Code เพิ่ม multiply(a, b) และ divide(a, b) ที่นี่

module.exports = { add, subtract };
